/** 文章目录（左侧导航 = “首页” + 以下目录） */
export interface Category {
  /** 目录唯一标识，与 Article.cat 对应 */
  id: string
  /** 展示名称（中文） */
  name: string
  /** 英文名 / 副标 */
  en: string
  /** 目录图标 */
  icon: string
  /** 图标宽度（px） */
  w: number
  /** 图标高度（px） */
  h: number
}